"""Build heuristics.yaml from Robbes et al.'s pattern CSVs plus local_rules.yaml.

Robbes match author patterns as unanchored regexes against "name <email>".
Plain-word patterns (e.g. "aider", "Claude") then also match human names
such as "Haider" or "Jean-Claude", so we wrap those in letter boundaries.
File patterns are anchored the same way Robbes' load_patterns() does.
"""
import csv
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "robbes_agent_impact"
OUT = ROOT / "heuristics.yaml"

# Robbes CSV name -> our rule level
LEVELS = {
    "authors": "author",
    "bots": "bot",
    "branches": "pr_branch",
    "labels": "pr_label",
    "files": "file",
}

PLAIN_WORD = re.compile(r"^[A-Za-z][A-Za-z0-9 .\-]*$")


def slug(text):
    return re.sub(r"\W+", "_", text).strip("_").lower()


def convert(level, pattern):
    """Return (regex, note) for one Robbes pattern."""
    if level == "file":
        # Same transformation as Robbes load_patterns(is_files=True)
        if "." in pattern and "\\." not in pattern:
            pattern = pattern.replace(".", "\\.")
        if not pattern.startswith("(?:^|/)") and not pattern.startswith("^"):
            pattern = "(?:^|/)" + pattern
        return pattern, ""
    if level in ("author", "bot") and "@" not in pattern and PLAIN_WORD.match(pattern):
        escaped = pattern.replace(".", "\\.")
        return (rf"(?<![A-Za-z-]){escaped}(?![A-Za-z-])",
                "letter boundaries added (avoids Haider/Jean-Claude matches)")
    return pattern, ""


def main():
    if not (SRC / "authors.csv").exists():
        sys.exit(f"missing {SRC.relative_to(ROOT)}: download the Robbes et al. pattern files first (see README)")
    rules = []
    seen = set()
    for name, level in LEVELS.items():
        with open(SRC / f"{name}.csv", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                raw = row["pattern"].strip()
                agent = row["subtype"].strip()
                if (level, raw) in seen:  # bots.csv repeats some rows
                    continue
                seen.add((level, raw))
                pattern, note = convert(level, raw)
                if level == "file" and raw == "AGENTS.md":
                    agent, note = "unknown", "used by many agents; does not identify one (Robbes 4.1.3)"
                rule_id = f"robbes_{level}_{slug(raw)}"
                n = 2
                while rule_id in {r["id"] for r in rules}:  # e.g. glm-4.7 vs GLM-4.7
                    rule_id = f"robbes_{level}_{slug(raw)}_{n}"
                    n += 1
                rules.append({
                    "id": rule_id,
                    "level": level,
                    "pattern": pattern,
                    "agent": agent,
                    "source": "robbes",
                    "robbes_pattern": raw,
                    "note": note,
                })

    local = yaml.safe_load((ROOT / "local_rules.yaml").read_text()) or []
    for r in local:
        r["source"] = "local"
        rules.append(r)

    ids = [r["id"] for r in rules]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        sys.exit(f"duplicate rule ids: {sorted(dupes)}")
    for r in rules:
        re.compile(r["pattern"])  # fail early on a bad regex

    header = ("# GENERATED by src/01_build_heuristics.py. Do not edit by hand.\n"
              "# Edit local_rules.yaml, or drop a rule after validation, then rerun.\n")
    OUT.write_text(header + yaml.safe_dump(rules, sort_keys=False, allow_unicode=True))
    counts = {}
    for r in rules:
        counts[r["level"]] = counts.get(r["level"], 0) + 1
    print(f"wrote {OUT.name}: {len(rules)} rules {counts}")


if __name__ == "__main__":
    main()
